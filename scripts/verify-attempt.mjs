// Offline verification of the retained unplanned failure; never broadcasts.
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {abi} from 'genlayer-js';
import {studionet} from 'genlayer-js/chains';
import {parseTransaction,recoverTransactionAddress,decodeFunctionData,fromRlp,hexToBytes,keccak256} from 'viem';
import {sha256} from '../lib/evidence.js';
import {lifecycleStatus,consensusResult} from '../lib/receipt.js';
const root=new URL('../',import.meta.url),failure='0x5b92e7f916ce8dbf91e15d09190bb885eedfa57103eb7912fddde6e2e9b1239f';
const row=JSON.parse(await readFile(new URL(`public/evidence/attempts/manual-conflict-${failure}.json`,root),'utf8'));
assert.equal(row.hash,failure);assert.ok(['FINALIZED','UNDETERMINED'].includes(lifecycleStatus(row)));
assert.equal(consensusResult(row),'MAJORITY_DISAGREE');assert.equal(row.leader_only,false);
assert.match(row.sourceSha256,/^[a-f0-9]{64}$/);
assert.equal(sha256(await readFile(new URL(`public/evidence/attempts/source-${row.sourceSha256}.py`,root),'utf8')),row.sourceSha256);
assert.equal(row.deploymentSnapshot.sourceSha256,row.sourceSha256);
const {spec}=row.savedIntent,address=value=>value.toLowerCase();
assert.equal(row.savedIntent.label,'manual-conflict-v1-attest');assert.equal(spec.method,'attest_merge');
assert.equal(spec.value,'0');assert.equal(spec.leaderOnly,false);assert.equal(spec.actor,row.actors.right);
assert.equal(address(spec.address),address(row.deploymentSnapshot.address));
assert.equal(address(row.from_address),address(spec.actor));assert.equal(address(row.to_address),address(spec.address));
assert.equal(spec.args[0],row.actors.coordinator);assert.equal(spec.args[1],'manual-conflict-v1');assert.equal(spec.args[2],1);assert.match(spec.args[3],/^[a-f0-9]{64}$/);
const signed=row.signed_rollup_transaction;assert.equal(keccak256(signed),failure);
const envelope=parseTransaction(signed);assert.equal(envelope.chainId,61999);assert.equal(envelope.value??0n,0n);
assert.equal(address(envelope.to),address(studionet.consensusMainContract.address));
assert.equal(address(await recoverTransactionAddress({serializedTransaction:signed})),address(spec.actor));
const submitted=decodeFunctionData({abi:studionet.consensusMainContract.abi,data:envelope.data});
assert.equal(submitted.functionName,'addTransaction');assert.equal(address(submitted.args[0]),address(spec.actor));assert.equal(address(submitted.args[1]),address(spec.address));
assert.equal(submitted.args[4].slice(2).toLowerCase(),row.tx_data.replace(/^0x/,'').toLowerCase());
const app=fromRlp(submitted.args[4]);assert.equal(app.length,2);assert.ok(app[1]==='0x'||BigInt(app[1])===0n);
const expected=abi.calldata.encode(abi.calldata.makeCalldataObject(spec.method,spec.args,undefined));
assert.deepEqual(hexToBytes(app[0]),expected);assert.deepEqual(Uint8Array.from(row.data.calldata.raw),expected);
const leader=row.consensus_data.leader_receipt.filter(entry=>entry.mode==='leader').at(-1);
const reason='Conflict pairs must be unique, sorted candidate IDs';
assert.equal(leader.execution_result,'ERROR');assert.equal(leader.result.status,'rollback');assert.equal(leader.result.payload,reason);
assert.equal(leader.eq_outputs['0'].status,'rollback');assert.equal(leader.eq_outputs['0'].payload,reason);
console.log(JSON.stringify({verifiedAttempt:true,completedWorkflow:false,hash:failure,lifecycle:lifecycleStatus(row),consensus:consensusResult(row),execution:'ERROR',rollback:reason,signedActorValueAndCalldataVerified:true},null,2));
